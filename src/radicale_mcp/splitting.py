"""Build two standards-compliant recurrence resources before any network writes."""

from copy import deepcopy
from datetime import UTC, date, datetime
from itertools import islice, zip_longest
from typing import Any, cast
from zoneinfo import ZoneInfo

from dateutil.rrule import rrulestr
from icalendar import Calendar, Event, vRecur

from .errors import CalendarError
from .events import event_span, master_event
from .recurrence import (
    key,
    not_found,
    occurrence_event,
    parse_occurrence,
    unsupported,
    validate_rule,
    validate_structure,
    values,
)
from .timeutils import localize


def before(left: date | datetime, right: date | datetime) -> bool:
    if isinstance(left, datetime) and isinstance(right, datetime) and left.tzinfo:
        return left.astimezone(UTC) < right.astimezone(UTC)
    return left < right


def partition_dates(master: Event, boundary: date | datetime, past: bool) -> None:
    """Keep EXDATE/RDATE parameters and original value types on their respective side."""
    for name in ("EXDATE", "RDATE"):
        properties = deepcopy(values(master, name))
        master.pop(name, None)
        for prop in properties:
            selected = [v.dt for v in prop.dts if before(v.dt, boundary) == past]
            if selected:
                master.add(name, selected, parameters=deepcopy(prop.params))


def split_calendar(
    calendar: Calendar, occurrence_id: str, tz: ZoneInfo, limit: int
) -> tuple[Calendar | None, Calendar, int]:
    """Partition by ORIGINAL recurrence ID; COUNT counts generated slots, not exclusions.

    RRULE evaluation is delegated to dateutil. Only daily or coarser supported
    rules are accepted. History enumeration is bounded by the configured cap.
    """
    master = validate_structure(calendar)
    validate_rule(
        master, cast(vRecur, master["RRULE"]).to_ical().decode() if "RRULE" in master else None
    )
    rid = parse_occurrence(occurrence_id, master, tz)
    occurrence_event(calendar, occurrence_id, tz, limit)  # Membership and DST validation.
    anchor = master.decoded("DTSTART")
    dt = anchor if isinstance(anchor, datetime) else datetime.combine(anchor, datetime.min.time())
    generated = rrulestr(cast(vRecur, master["RRULE"]).to_ical().decode(), dtstart=dt)
    count = 0
    for value in generated:
        candidate = value if isinstance(anchor, datetime) else value.date()
        if isinstance(candidate, datetime):
            localize(candidate.replace(tzinfo=None), candidate.tzinfo or tz, existing=True)
        if not before(candidate, rid):
            if key(candidate) != key(rid):
                raise unsupported(
                    "A future boundary must be generated by the RRULE, not only RDATE."
                )
            break
        count += 1
        if count > limit:
            raise CalendarError("limit_exceeded", "Too much recurrence history to split safely.")
    else:
        raise not_found()

    past, future = deepcopy(calendar), deepcopy(calendar)
    for target, is_past in ((past, True), (future, False)):
        target.subcomponents = [
            c
            for c in target.subcomponents
            if c.name != "VEVENT"
            or "RECURRENCE-ID" not in c
            or before(c.decoded("RECURRENCE-ID"), rid) == is_past
        ]
        partition_dates(master_event(target), rid, is_past)

    old, new = master_event(past), master_event(future)
    old_rule, new_rule = cast(vRecur, old["RRULE"]), cast(vRecur, new["RRULE"])
    old_rule.pop("UNTIL", None)
    old_rule["COUNT"] = [count]
    if "COUNT" in new_rule:
        new_rule["COUNT"] = [int(new_rule["COUNT"][0]) - count]

    # Derive the unmodified instance from the master, not an individual override.
    plain = deepcopy(calendar)
    plain.subcomponents = [c for c in plain.subcomponents if c.name != "VEVENT"]
    clean = deepcopy(master)
    clean.pop("EXDATE", None)
    plain.add_component(clean)
    instance = occurrence_event(plain, occurrence_id, tz, limit)
    for name in ("DTSTART", "DTEND", "DURATION"):
        new.pop(name, None)
        if name in instance:
            new[name] = deepcopy(instance[name])
    event_span(new, tz)
    validate_rule(new)
    # Re-anchoring can change defaults inferred by dateutil. Compare the suffix
    # through the configured occurrence cap as an additional consistency check.
    # Supported daily-or-coarser rules re-anchor in the same recurrence period;
    # the comparison below additionally catches inferred month/day changes.
    new_anchor = new.decoded("DTSTART")
    new_dt = (
        new_anchor
        if isinstance(new_anchor, datetime)
        else datetime.combine(new_anchor, datetime.min.time())
    )
    suffix = rrulestr(new_rule.to_ical().decode(), dtstart=new_dt)
    original_suffix = generated.xafter(new_dt, inc=True)
    for original, replacement in zip_longest(
        islice(original_suffix, limit + 1), islice(suffix, limit + 1)
    ):
        if original != replacement:
            raise unsupported("This rule cannot be re-anchored without changing its pattern.")
    if count == 0:
        # There cannot be an earlier generated occurrence, but an RDATE/override
        # may precede DTSTART. Keeping that requires a separate representation.
        if len(past.walk("VEVENT")) > 1 or "RDATE" in old:
            raise unsupported("Occurrences before the rule anchor require a calendar client.")
        return None, future, count
    return past, future, count


def has_future_exceptions(calendar: Calendar) -> bool:
    master = master_event(calendar)
    return len(calendar.walk("VEVENT")) > 1 or any(p in master for p in ("EXDATE", "RDATE"))


def set_uid(calendar: Calendar, uid: str, parent_uid: str) -> None:
    for event in cast(list[Event], calendar.walk("VEVENT")):
        event.pop("UID", None)
        event.add("UID", uid)
        # Only the master carries the relationship, avoiding unrelated-property loss.
    master_event(calendar).add("RELATED-TO", parent_uid, parameters={"RELTYPE": "SIBLING"})


def recovery_details(calendar_id: str, original_id: str, successor_id: str) -> dict[str, Any]:
    return {
        "calendar_id": calendar_id,
        "original_event_id": original_id,
        "successor_event_id": successor_id,
        "action": "Read both resources and review their boundaries before any retry or cleanup.",
    }
